from razbor.reader import PageText, ReadResult  # noqa: E402

fails = 0


def check(cond: bool, text: str) -> None:
    global fails
    print(("  ok   " if cond else "  FAIL ") + text)
    if not cond:
        fails += 1


def load(name: str) -> str:
    with open(os.path.join(ROOT, "tests", "texts", name), encoding="utf-8") as fh:
        return fh.read()


def read(text: str):
    rr = ReadResult(pages=[PageText(1, text, "text")], page_count=1)
    return rr, analyze(rr)


