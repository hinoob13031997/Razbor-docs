"""Чтение полей из готового текста (без распознавания сканов). Запуск: python tests/test_fields.py

Тексты вымышленные, лежат в tests/texts. Проверяется то, что раньше читалось неверно:
определение о правопреемстве, исполнительский сбор, ФИО в разных видах записи.
"""
from __future__ import annotations

import os
import sys
from datetime import date
from decimal import Decimal

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from razbor import classify as C  # noqa: E402
from razbor import fields as F  # noqa: E402

fails = 0


def check(cond: bool, text: str) -> None:
    global fails
    print(("  ok   " if cond else "  FAIL ") + text)
    if not cond:
        fails += 1


def read(text: str):
    doc = F.Doc([text])
    cl = C.classify(doc.text)
    return cl, F.extract(doc, cl.key, cl.group), F.find_flags(doc, cl.group, cl.key), F.find_identifiers(doc)


def val(f, name):
    h = f.get(name)
    return h.value if h is not None else None


def load(name: str) -> str:
    with open(os.path.join(ROOT, "tests", "texts", name), encoding="utf-8") as fh:
        return fh.read()


print("Определение о правопреемстве")
cl, f, flags, ids = read(load("succession_ruling.txt"))
check(cl.key == "succession", f"вид документа: {cl.label}")
check(val(f, "Номер дела") == "2-4321/2023", "номер дела")
check(val(f, "Дата документа") == date(2023, 6, 14), "дата определения")
check(val(f, "Суд") == "Октябрьский районный суд г. Новограда", "суд")
check(val(f, "ФИО") == "Петрову Ивану Сергеевичу", "должник")
check(val(f, "Кого заменили") == "ООО «АБВ»", "кого заменили")
check(val(f, "На кого заменили") == "Кузнецову Елену Петровну", "на кого заменили")
check(val(f, "Взыскатель / кредитор") == "Кузнецову Елену Петровну", "новый взыскатель — правопреемник")
check(val(f, "Дата уступки") == date(2023, 6, 2), "дата договора уступки")
check(val(f, "Номер договора") == "РК-123456/АКк 60/2013/01-01/12345", "номер договора с пробелом внутри")
check(val(f, "Сумма основная") == Decimal("187450.36"), "сумма иска")
check(val(f, "Госпошлина") == Decimal("5249.00"), "госпошлина")
check(val(f, "VIN (залог)") == "XTA210990D1234567", "VIN залога")
check(flags == ["правопреемство / цессия"], f"признаки: {flags} (смерти нет: это цитата ст. 44 ГПК)")
check("РК-123456/АКк 60/2013/01-01/12345" in ids["contracts"], "номер договора попал в список для привязки")

print("Постановление об окончании ИП: исполнительский сбор")
cl, f, flags, ids = read(load("fssp_end_with_fee.txt"))
check(cl.key == "fssp_end", f"вид документа: {cl.label}")
check(val(f, "Сумма основная") == Decimal("220784.12"), "основная сумма — остаток основного долга")
check(val(f, "Исполнительский сбор") == Decimal("15454.89"), "исполнительский сбор записан отдельно")
check(val(f, "ФИО") == "ГОРОДЕЦКАЯ МАРИЯ СЕРГЕЕВНА", "ФИО с фамилией на «город…»")
check(val(f, "Дата рождения") == date(1985, 5, 12), "дата рождения")
check(val(f, "Основание окончания", ).startswith("ст. 46 ч. 1 п. 3"), "основание окончания")

cl, f, flags, ids = read(load("fssp_end_fee_only.txt"))
check("Сумма основная" not in f, "только сбор в тексте — основной суммы нет")
check(val(f, "Исполнительский сбор") == Decimal("7000.00"), "сбор 7 000 найден")
check(val(f, "ФИО") == "КУЗНЕЦОВ ПЕТР АЛЕКСЕЕВИЧ", "ФИО на следующей строке после «в отношении должника:»")

print("ФИО в разных видах записи")
base = "ПОСТАНОВЛЕНИЕ\nоб окончании исполнительного производства\n05.03.2024\nСудебный пристав-исполнитель Образцов А.Б.,\n"
cases = [
    ("в отношении должника: Иванов Иван Иванович, 01.02.1980 г.р.", "Иванов Иван Иванович"),
    ("в отношении должника (заемщика): ИВАНОВ ИВАН ИВАНОВИЧ, ИНН 770000000000", "ИВАНОВ ИВАН ИВАНОВИЧ"),
    ("по делу о взыскании с гражданина ИВАНОВ ИВАН ИВАНОВИЧ, ИНН 770000000000", "ИВАНОВ ИВАН ИВАНОВИЧ"),
    ("ОСП ПО ТЕСТОВОМУ РАЙОНУ ИВАНОВ ИВАН ИВАНОВИЧ ИНН 770000000000", "ИВАНОВ ИВАН ИВАНОВИЧ"),
    ("Должник: Банков Сергей Петрович, 02.03.1970 г.р.", "Банков Сергей Петрович"),
    ("ИВАНОВА ОЛЬГА ПЕТРОВНА 03.04.1980 г.р., ИНН 770000000000", "ИВАНОВА ОЛЬГА ПЕТРОВНА"),
]
for line, want in cases:
    _, f, _, _ = read(base + line + "\nУСТАНОВИЛ: окончить производство. Остаток долга 1 000,00 руб.")
    check(val(f, "ФИО") == want, f"{line[:60]!r} -> {val(f, 'ФИО')!r}")

print("Организации не принимаются за людей")
for org in ("Общество с ограниченной ответственностью", "Управление Федеральной службы Российской Федерации",
            "Отдел судебных приставов Тестового района"):
    check(not F.looks_like_person(org), org)
check(F.looks_like_person("Городецкий Иван Петрович"), "Городецкий Иван Петрович")

print("Номер договора")
for text, want in [
    ("задолженность по кредитному договору от 6 августа 2013 г. №РК-351182/АКк\n60/2013/01-01/36644 в размере", "РК-351182/АКк 60/2013/01-01/36644"),
    ("по договору займа № ЗМ-2022/778 от 10.06.2022 в размере", "ЗМ-2022/778"),
    ("по кредитному договору № КД-778899, ответчик", "КД-778899"),
]:
    _, f, _, _ = read("ЗАОЧНОЕ РЕШЕНИЕ\nИменем Российской Федерации\n20 июля 2023 года\nрешил: взыскать " + text)
    check(val(f, "Номер договора") == want, f"{want}")

print(f"\nрасхождений: {fails}")
sys.exit(1 if fails else 0)
