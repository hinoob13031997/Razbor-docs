def wrap_lines(text: str, width: int) -> list[str]:
    out: list[str] = []
    for line in text.split("\n"):
        out += textwrap.wrap(line, width=width, replace_whitespace=False, drop_whitespace=False) or [""]
    return out


def make_text_pdf(path: str, pages: list[str]) -> None:
    from reportlab.lib.pagesizes import A4
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.pdfgen import canvas

    if "DV" not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont("DV", FONT))
    c = canvas.Canvas(path, pagesize=A4)
    w, h = A4
    for page in pages:
        c.setFont("DV", 10.5)
        y = h - 60
        for line in wrap_lines(page, 78):
            c.drawString(50, y, line)
            y -= 15
        c.showPage()
    c.save()


def render_page(text: str, rotate: int = 0, noise: bool = False, seed: int = 1) -> Image.Image:
    rnd = random.Random(seed)
    W, H = 1654, 2339  # A4, 200 dpi
    img = Image.new("L", (W, H), 255)
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(FONT, 27)
    y = 140
    for line in wrap_lines(text, 74):
        d.text((130, y), line, font=font, fill=20)
        y += 40
    if rotate:
        img = img.rotate(rotate, expand=True, fillcolor=255)
    # слабый наклон и лёгкая «грязь», как у обычных сканов
    img = img.rotate(rnd.uniform(-0.5, 0.5), resample=Image.BICUBIC, fillcolor=255)
    px = img.load()
    amount = 0.006 if noise else 0.003
    for _ in range(int(img.width * img.height * amount)):
        x, yy = rnd.randrange(img.width), rnd.randrange(img.height)
        px[x, yy] = rnd.choice((0, 60, 200))
    if noise:
        img = img.filter(ImageFilter.GaussianBlur(0.9))
    return img


def make_scan_pdf(path: str, pages: list[str], rotate=0, noise=False) -> None:
    imgs = [render_page(t, rotate, noise, seed=i + 7) for i, t in enumerate(pages)]
    imgs[0].save(path, "PDF", resolution=200, save_all=True, append_images=imgs[1:])


def main(out: str) -> None:
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(os.path.join(out, "вложенная папка"))
    expected = {}
    for d in DOCS:
        path = os.path.join(out, d["name"])
        if d["kind"] == "text":
            make_text_pdf(path, d["pages"])
        else:
            make_scan_pdf(path, d["pages"], **d["opts"])
        expected[d["name"]] = d["expect"]

    # точная копия файла в другой папке
    shutil.copy(os.path.join(out, "01_sud_prikaz.pdf"), os.path.join(out, "вложенная папка", "копия приказа.pdf"))
    expected["вложенная папка/копия приказа.pdf"] = {"type": "order", "dup_file_of": "01_sud_prikaz.pdf"}

    # скан как картинка (jpg)
    img = render_page(DOCS[0]["pages"][0], seed=99)
    img.convert("RGB").save(os.path.join(out, "вложенная папка", "фото_приказа.jpg"), quality=85)
    expected["вложенная папка/фото_приказа.jpg"] = {"type": "order"}

    # пароль, битый файл, пустой PDF
    import pikepdf

    with pikepdf.open(os.path.join(out, "04_ispolnitelny_list.pdf")) as pdf:
        pdf.save(os.path.join(out, "20_protected.pdf"),
                 encryption=pikepdf.Encryption(owner="o", user="u"))
    with open(os.path.join(out, "21_broken.pdf"), "wb") as f:
        f.write(b"%PDF-1.4\nthis is not a real pdf" + os.urandom(200))
    Image.new("L", (800, 1000), 255).save(os.path.join(out, "22_blank_page.pdf"), "PDF")
    expected["20_protected.pdf"] = {"error": "паролем"}
    expected["21_broken.pdf"] = {"error": "повреждён"}
    expected["22_blank_page.pdf"] = {"review": "текст не найден"}

    with open(os.path.join(out, "expected.json"), "w", encoding="utf-8") as f:
        json.dump(expected, f, ensure_ascii=False, indent=1)
    print("создано файлов:", len(expected), "в", out)


