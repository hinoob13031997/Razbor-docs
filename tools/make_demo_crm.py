NAMES = ["Алексей", "Борис", "Виктор", "Глеб", "Дмитрий", "Егор", "Илья", "Кирилл", "Лев", "Максим"]
PAT = ["Алексеевич", "Борисович", "Викторович", "Олегович", "Петрович", "Сергеевич"]


def rnd_row(rng: random.Random, i: int) -> list:
    d0 = date(2018, 1, 1) + timedelta(days=rng.randint(0, 1800))
    b = date(1955, 1, 1) + timedelta(days=rng.randint(0, 17000))
    last = date.today() - timedelta(days=rng.randint(30, 1000))
    debt = round(rng.uniform(5000, 900000), 2)
    st = rng.choice(["Досудебная", "Суд", "ФССП", "Досудебная", "Досудебная"])
    case = f"2-{rng.randint(100, 9999)}/{rng.randint(2019, 2024)}" if st != "Досудебная" else ""
    return [f"Т-{i:07d}", d0.isoformat(), f"{rng.choice(SUR)}{rng.choice(['', 'а'])} {rng.choice(NAMES)} {rng.choice(PAT)}",
            b.strftime("%d.%m.%Y"), "", debt, last.isoformat(), st, round(debt * 0.8, 2), case, "", "", "", "", "",
            f"u{rng.randint(1, 30):02d}", ""]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--rows", type=int, default=0)
    ap.add_argument("--blocks", type=int, default=1, help="строк на договор (блоки суда, ФССП и т. п.)")
    a = ap.parse_args()
    rng = random.Random(1)
    with open(a.out, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(HEAD)
        for r in CORE:
            w.writerow(r)
        n = a.rows if a.rows else 16
        for i in range(n):
            r = rnd_row(rng, i + 1)
            w.writerow(r)
            for b in range(1, a.blocks):  # доп. строки того же договора: только часть колонок заполнена
                extra = [r[0]] + [""] * (len(r) - 1)
                if b == 1:
                    extra[9], extra[10] = r[9] or f"2-{rng.randint(100, 9999)}/2023", "2023-0%d-15" % rng.randint(1, 9)
                elif b == 2:
                    extra[11], extra[12] = f"ФС {rng.randint(10**8, 10**9 - 1)}", "2024-0%d-10" % rng.randint(1, 9)
                w.writerow(extra)


if __name__ == "__main__":
    main()
