# между словами в сканах встречаются случайные знаки: «ПОСТАНОВЛЕНИЕ |  об окончании»
GAP = r"[\s|.,;:_‚`'’‘\-<>~*=+]+"


def _gap(rx: str) -> str:
    return rx.replace(r"\s+", GAP)


def _title(*phrases: str) -> str:
    """Регулярное выражение для заголовка: отдельная строка, ПРОПИСНЫМИ или Заглавной."""
    alts: list[str] = []
    for ph in phrases:
        body = r"\s+".join(re.escape(w) for w in ph.split())
        cap = r"\s+".join(re.escape(w) for w in ph.capitalize().split())
        up = r"\s+".join(re.escape(w) for w in ph.upper().split())
        alts += [up, cap]
    return r"^[\W_]*(?:" + "|".join(alts) + r")\b(?=[ \t]*(?:№|N\b|\n|$|\(|,|\||\.|:|по\b|о\b|об\b))"


@dataclass(frozen=True)
class Rule:
    key: str
    label: str
    group: str
    patterns: tuple  # (regex, weight, zone, flags)


def _p(regex: str, weight: int, zone: str = "all", flags: int = re.I | re.M):
    return (re.compile(_gap(regex), flags), weight, zone)


def _t(weight: int, *phrases: str):
    return (re.compile(_gap(_title(*phrases)), re.M), weight, "head")


